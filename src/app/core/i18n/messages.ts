export type MessageKey = keyof typeof MESSAGES;

/** Replacement parameters for `{placeholder}` tokens. */
export type MessageParams = Readonly<Record<string, string | number>>;

/** Replaces `{name}` tokens. Unknown tokens are left untouched. */
export function interpolate(message: string, params?: MessageParams): string {
  if (!params) {
    return message;
  }
  return message.replace(/\{(\w+)\}/g, (match, token: string) => {
    const value = params[token];
    return value === undefined ? match : String(value);
  });
}
